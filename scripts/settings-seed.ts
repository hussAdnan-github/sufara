// Prints the SQL that seeds platform_settings v1 from DEFAULT_CONFIG.
// npx vite-node scripts/settings-seed.ts > supabase/migrations/20261101000300_seed_settings.sql
import { DEFAULT_CONFIG, normalizeConfig } from '../src/config/platform';

const cfg = normalizeConfig(DEFAULT_CONFIG);
const payload = JSON.stringify(cfg).replace(/'/g, "''");
console.log(`-- GENERATED by scripts/settings-seed.ts — Decision Log v1 defaults.
-- Seeds version 1 only when the table is empty, so it never overrides a
-- version an admin has published.
insert into public.platform_settings (version, effective_from, note, payload, created_by)
select 1, date '${cfg.effectiveFrom}', '${cfg.note.replace(/'/g, "''")}', '${payload}'::jsonb, 'decision-log'
where not exists (select 1 from public.platform_settings);`);

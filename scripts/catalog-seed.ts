// Generates the catalogue seed from the storefront mocks so the database
// starts with exactly what the shop shows today.
// npx vite-node scripts/catalog-seed.ts > supabase/migrations/20261101000500_seed_catalog.sql
import { categories, factories, products } from '../src/mocks/shop';
import { productText } from '../src/mocks/catalog/en/products';
import { factoryText } from '../src/mocks/catalog/en/factories';
import { categoryText } from '../src/mocks/catalog/en/categories';
import { parseWeightKg } from '../src/pages/shop/lib/shipping';

const q = (v: unknown) => (v === null || v === undefined ? 'null' : `'${String(v).replace(/'/g, "''")}'`);
const en = <T extends Record<string, Record<string, unknown>>>(map: T, id: string, key: string) =>
  (map[id]?.[key] as string | undefined) ?? '';

const out: string[] = [
  '-- GENERATED by scripts/catalog-seed.ts from src/mocks — the launch catalogue.',
  '-- Idempotent: existing rows are left untouched (on conflict do nothing).',
  '',
];

categories.forEach((c, i) => {
  out.push(`insert into public.categories (id, name_ar, name_en, icon, sort_order) values (${q(c.id)}, ${q(c.name)}, ${q(en(categoryText as never, c.id, 'name'))}, ${q(c.icon)}, ${i}) on conflict (id) do nothing;`);
});
out.push('');

factories.forEach((f) => {
  out.push(`insert into public.factories (id, name_ar, name_en, city, kyb_status) values (${q(f.id)}, ${q(f.name)}, ${q(en(factoryText as never, f.id, 'name'))}, ${q(f.city)}, ${f.verified ? "'verified'" : "'pending'"}) on conflict (id) do nothing;`);
});
out.push('');

products.forEach((p) => {
  const t = (productText as Record<string, Record<string, unknown>>)[p.id] ?? {};
  const tiers = JSON.stringify(p.wholesale?.tiers ?? []);
  out.push(`insert into public.products (id, factory_id, category_id, name_ar, name_en, short_ar, short_en, image_url, price, weight_kg, hs_code, stock, moq, tiers, active) values (${[
    q(p.id), q(p.factoryId), q(p.categoryId), q(p.name), q(t.name ?? ''), q(p.shortDesc), q(t.shortDesc ?? ''), q(p.image),
    p.price, Number(parseWeightKg(p.weight).toFixed(3)), q(p.hs), p.stock, p.wholesale?.moq ?? 'null', `${q(tiers)}::jsonb`, 'true',
  ].join(', ')}) on conflict (id) do nothing;`);
});

console.log(out.join('\n'));

"""Regenerates supabase/tests/07_client_queries.sql: every table/column the
live screens select must exist in the schema (catches client/schema drift).
Usage: python3 scripts/gen-client-queries.py > supabase/tests/07_client_queries.sql"""
import glob
import re

files = glob.glob('src/pages/dashboard/views/live/*.tsx') + [
    'src/pages/dashboard/views/admin/FinanceLedger.tsx', 'src/lib/catalogSync.ts',
    'src/pages/dashboard/views/ambassador/LeaderTeam.tsx', 'src/pages/dashboard/views/admin/AdminAccounts.tsx',
    'src/pages/dashboard/views/admin/PromoCodesCard.tsx', 'src/pages/dashboard/components/NotificationBell.tsx',
]
pairs = set()
for f in sorted(files):
    s = open(f, encoding='utf-8').read()
    for t, cols in re.findall(r"from\('([a-z_]+)'\)\s*\.select\('([^']+)'\)", s, re.S):
        pairs.add((t, cols))
print("-- GENERATED by scripts/gen-client-queries.py: every column the dashboards select must exist (catches drift).")
print("\\set ON_ERROR_STOP 1")
for t, cols in sorted(pairs):
    plain = re.sub(r"[a-z_]+(:[a-z_]+)?\([^)]*\)", "", cols)
    plain = ",".join(c.strip() for c in plain.split(",") if c.strip())
    print(f"select {plain or '1'} from public.{t} limit 0;")
    for alias, rel, inner in re.findall(r"([a-z_]+)(?::([a-z_]+))?\(([^)]*)\)", cols):
        print(f"select {inner} from public.{rel or alias} limit 0;")
print("\\echo 'CLIENT QUERY CHECKS PASSED'")
